function Setup_All()
%SETUP_ALL  One-time setup and health check of the whole EV Digital Twin project (MATLAB + website).
%   Run it once after copying the folder, and again whenever something looks wrong.
%   It changes nothing in the model. It only checks, creates the results folder and the website config.
root = fileparts(mfilename('fullpath'));
cd(root);  addpath(root);  rehash;
nOK = 0;  nWarn = 0;  nBad = 0;
fprintf('\n==== EV DIGITAL TWIN - Setup_All ====\nFolder: %s\n', root);

fprintf('\n[1] MATLAB and products\n');
rel = version('-release');
if strcmp(rel,'2024b'), ok(['MATLAB R' rel]); else, warn(['MATLAB R' rel ' (project built in R2024b)']); end
v = ver;  names = {v.Name};
prod = {'Simulink','Simscape','Simscape Electrical','Simscape Battery'};
for k = 1:numel(prod)
    if any(strcmp(names, prod{k})), ok(prod{k}); else, bad([prod{k} ' NOT installed']); end
end

fprintf('\n[2] Required MATLAB project files\n');
req = {'RunAll.m','EV_DAQ_Builder_V7.m','BLDCSpeedControl_EV_Layout_v2.slx','BLDCSpeedControlData.m', ...
       'BLDCSpeedControlInput.mat','Batteries2_lib.slx'};
for k = 1:numel(req)
    if exist(fullfile(root,req{k}),'file') == 2, ok(req{k}); else, bad(['MISSING ' req{k}]); end
end
if exist(fullfile(root,'+Batteries2'),'dir') == 7, ok('+Batteries2 (battery package folder)');
else, bad('MISSING folder +Batteries2 (generated by Simscape Battery Builder; copy it from your original project)'); end
opt = {'Batteries2.slx','EV_SysID_Auto.m','push_to_website.m','RunAll_and_Push.m'};
for k = 1:numel(opt)
    if exist(fullfile(root,opt{k}),'file') == 2, ok([opt{k} ' (optional)']); else, warn(['missing optional ' opt{k}]); end
end

fprintf('\n[3] Folders\n');
if exist(fullfile(root,'results'),'dir') ~= 7, mkdir(fullfile(root,'results')); end
ok('results/');

fprintf('\n[4] Website files (folder website/)\n');
web = {'index.html','model.js','package.json','vercel.json',fullfile('api','runs.js'),fullfile('api','simulate.js')};
for k = 1:numel(web)
    if exist(fullfile(root,'website',web{k}),'file') == 2, ok(web{k}); else, warn(['website/' web{k} ' missing']); end
end

fprintf('\n[5] Website connection\n');
cfgFile = fullfile(root,'EV_Website_Config.m');
if exist(cfgFile,'file') ~= 2
    if exist(fullfile(root,'EV_Website_Config_template.m'),'file') == 2
        t = fileread(fullfile(root,'EV_Website_Config_template.m'));
        t = strrep(t,'EV_Website_Config_template','EV_Website_Config');
        fid = fopen(cfgFile,'w');  fwrite(fid,t);  fclose(fid);  rehash;
        warn('Created EV_Website_Config.m - open it and type your site URL and API key (after the Vercel deploy)');
    else
        warn('EV_Website_Config_template.m missing');
    end
else
    cfg = EV_Website_Config();
    if contains(cfg.siteUrl,'YOUR-SITE')
        warn('EV_Website_Config.m still has the placeholder URL');
    else
        try
            r = webread([regexprep(cfg.siteUrl,'/+$','') '/api/runs'], weboptions('Timeout',15));
            ok(sprintf('Website online, %d saved run(s)', numel(r)));
        catch err
            warn(['Website not reachable: ' err.message]);
        end
    end
end

fprintf('\n==== SUMMARY   OK %d   WARN %d   FAIL %d ====\n', nOK, nWarn, nBad);
if nBad == 0
    fprintf('Next: RunAll  (simulate)   or   RunAll_and_Push  (simulate and send to the website)\n\n');
else
    fprintf('Fix the FAIL lines first, then run Setup_All again.\n\n');
end

    function ok(s),   nOK = nOK + 1;     fprintf('  [ OK ] %s\n', s); end
    function warn(s), nWarn = nWarn + 1; fprintf('  [WARN] %s\n', s); end
    function bad(s),  nBad = nBad + 1;   fprintf('  [FAIL] %s\n', s); end
end
